-- ============================================================
-- Vben Admin 配套后端 RBAC 表结构（对齐若依 RuoYi-Vue 经典模型）
-- PostgreSQL 版本。首次部署：先建库
--   CREATE DATABASE vben5;
-- 再执行本文件。所有语句幂等（IF NOT EXISTS），
-- 配合 spring.sql.init.mode: always 可每次启动重复执行。
-- 注意：update_time 自动更新由应用层 MyBatis-Plus MetaObjectHandler 完成，
-- 本脚本不包含 PL/pgSQL 函数/触发器（Spring SQL 初始化器不支持 $$ 美元引用）。
-- ============================================================

-- 知识库向量检索依赖 pgvector 扩展（bitnami/postgresql:18+ 自带；仅 PostgreSQL）
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS sys_user (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username    VARCHAR(64)  NOT NULL,
  password    VARCHAR(128) NOT NULL,
  nickname    VARCHAR(64)  NOT NULL DEFAULT '',
  home_path   VARCHAR(255) NULL,
  dept_id     BIGINT       NULL,
  status      SMALLINT     NOT NULL DEFAULT 0,
  create_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_user_username UNIQUE (username)
);
CREATE INDEX IF NOT EXISTS idx_user_dept ON sys_user (dept_id);
CREATE TABLE IF NOT EXISTS sys_user_recovery_email (
  user_id BIGINT PRIMARY KEY REFERENCES sys_user(id) ON DELETE CASCADE,
  email VARCHAR(255) NOT NULL,
  verified_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE sys_user IS '用户表';
COMMENT ON COLUMN sys_user.password IS 'BCrypt 哈希';
COMMENT ON COLUMN sys_user.nickname IS '显示名(对应前端 realName)';
COMMENT ON COLUMN sys_user.home_path IS '登录后首页(可选)';
COMMENT ON COLUMN sys_user.dept_id IS '所属部门id(sys_dept.id),NULL=未归属';
COMMENT ON COLUMN sys_user.status IS '0正常 1停用';

