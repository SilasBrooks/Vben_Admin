-- ============================================================
-- 知识库：文档 + 向量块，pgvector 无固定维度列（兼容不同 embedding 选型）
-- 大文件管线：kb_file 物理文件去重载体 + kb_upload_session 分片会话
-- ============================================================
CREATE TABLE IF NOT EXISTS kb_doc (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_name     VARCHAR(255) NOT NULL,
  size_bytes    BIGINT       NOT NULL DEFAULT 0,
  chunk_count   INT          NOT NULL DEFAULT 0,
  status        SMALLINT     NOT NULL DEFAULT 0,
  error_msg     VARCHAR(500) NULL,
  uploader_id   BIGINT       NOT NULL,
  uploader_name VARCHAR(64)  NOT NULL DEFAULT '',
  create_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE kb_doc IS '知识库文档表(状态:0处理中 1完成 2失败)';
COMMENT ON COLUMN kb_doc.status IS '0=处理中,1=完成,2=失败(见error_msg)';

-- 大文件管线新增列：file_id 关联物理文件(NULL=旧路径正文入库)；stage/progress 管道可观测；
-- processed_chunks/total_chunks 为 embedding 断点续跑依据
ALTER TABLE kb_doc ADD COLUMN IF NOT EXISTS file_id BIGINT NULL;
ALTER TABLE kb_doc ADD COLUMN IF NOT EXISTS stage VARCHAR(16) NULL;
ALTER TABLE kb_doc ADD COLUMN IF NOT EXISTS progress INT NOT NULL DEFAULT 0;
ALTER TABLE kb_doc ADD COLUMN IF NOT EXISTS processed_chunks INT NOT NULL DEFAULT 0;
ALTER TABLE kb_doc ADD COLUMN IF NOT EXISTS total_chunks INT NOT NULL DEFAULT 0;
COMMENT ON COLUMN kb_doc.file_id IS '关联kb_file.id(NULL=正文直接入库的旧路径文档)';
COMMENT ON COLUMN kb_doc.stage IS '处理阶段:PARSING解析/CHUNKING切块/EMBEDDING向量化(完成置NULL)';
COMMENT ON COLUMN kb_doc.progress IS '处理进度百分比0-100(完成置100)';
COMMENT ON COLUMN kb_doc.processed_chunks IS '已完成向量化的块数(断点续跑依据)';
COMMENT ON COLUMN kb_doc.total_chunks IS '切块总块数(向量化阶段用于进度计算)';

CREATE TABLE IF NOT EXISTS kb_file (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sha256      CHAR(64)     NOT NULL,
  size        BIGINT       NOT NULL,
  storage_key VARCHAR(512) NOT NULL,
  ref_count   INT          NOT NULL DEFAULT 0,
  create_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE kb_file IS '知识库物理文件表(SHA-256去重,ref_count引用计数归零清理存储)';
COMMENT ON COLUMN kb_file.sha256 IS '整文件SHA-256(唯一,秒传判定依据)';
COMMENT ON COLUMN kb_file.storage_key IS 'StorageService存储键';
COMMENT ON COLUMN kb_file.ref_count IS '引用该文件的文档数(删除文档递减,归零清理存储)';
CREATE UNIQUE INDEX IF NOT EXISTS uk_kb_file_sha256 ON kb_file (sha256);

CREATE TABLE IF NOT EXISTS kb_upload_session (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  upload_id       VARCHAR(64)  NOT NULL,
  sha256          CHAR(64)     NOT NULL,
  file_name       VARCHAR(255) NOT NULL,
  file_size       BIGINT       NOT NULL,
  chunk_size      BIGINT       NOT NULL,
