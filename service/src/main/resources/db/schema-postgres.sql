-- 邮箱列（幂等添加，历史库升级用）
ALTER TABLE sys_user ADD COLUMN IF NOT EXISTS email VARCHAR(255) NULL;
COMMENT ON COLUMN sys_user.email IS '邮箱,NULL=未填写';
