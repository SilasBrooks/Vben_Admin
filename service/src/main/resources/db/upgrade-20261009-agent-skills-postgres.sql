-- 4. F 按钮权限
INSERT INTO sys_menu (parent_id, menu_name, menu_type, title, perm, visible, status)
SELECT m.id, 'Perm_System_Skill_' || split_part(p.perm, ':', 3), 'F', p.perm, p.perm, 0, 0
FROM sys_menu m
CROSS JOIN (VALUES ('System:Skill:List'), ('System:Skill:Add'), ('System:Skill:Edit'),
                   ('System:Skill:Delete')) AS p(perm)
WHERE m.menu_name = 'SystemSkill'
  AND NOT EXISTS (SELECT 1 FROM sys_menu f WHERE f.perm = p.perm);

-- 5. 授权给 super / admin
INSERT INTO sys_role_menu (role_id, menu_id)
SELECT r.id, m.id
FROM sys_role r
CROSS JOIN sys_menu m
WHERE r.role_key IN ('super', 'admin')
  AND (m.menu_name = 'SystemSkill'
       OR (m.menu_type = 'F' AND m.perm LIKE 'System:Skill:%'))
  AND NOT EXISTS (SELECT 1 FROM sys_role_menu rm
                  WHERE rm.role_id = r.id AND rm.menu_id = m.id);
