-- 1. pgvector 扩展
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Embedding 配置表
CREATE TABLE IF NOT EXISTS sys_embedding_config (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            VARCHAR(64)   NOT NULL,
  base_url        VARCHAR(255)  NOT NULL,
  api_key         VARCHAR(255)  NOT NULL DEFAULT '',
  model           VARCHAR(64)   NOT NULL,
  dimension       INT           NULL,
  timeout_seconds INT           NOT NULL DEFAULT 60,
  enabled         SMALLINT      NOT NULL DEFAULT 1,
  is_active       SMALLINT      NOT NULL DEFAULT 0,
  remark          VARCHAR(255)  NULL,
  create_time     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_emb_name UNIQUE (name)
);
COMMENT ON TABLE sys_embedding_config IS 'Embedding模型配置表(OpenAI兼容/embeddings,全局唯一激活)';

-- 3. 知识库文档/向量块表
CREATE TABLE IF NOT EXISTS kb_doc (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_name     VARCHAR(255) NOT NULL,
  size_bytes    BIGINT       NOT NULL DEFAULT 0,
  chunk_count   INT          NOT NULL DEFAULT 0,
  status        SMALLINT     NOT NULL DEFAULT 0,
  error_msg     VARCHAR(500) NULL,
  uploader_id   BIGINT       NOT NULL,
  uploader_name VARCHAR(64)  NOT NULL DEFAULT '',
  create_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE kb_doc IS '知识库文档表(状态:0处理中 1完成 2失败)';

CREATE TABLE IF NOT EXISTS kb_chunk (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_id     BIGINT  NOT NULL,
  seq        INT     NOT NULL DEFAULT 0,
  content    TEXT    NOT NULL,
  embedding  vector  NULL,
  create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_kb_chunk_doc ON kb_chunk (doc_id);

