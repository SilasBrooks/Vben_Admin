-- 1. 建表（用例与运行随集合外键级联删除）
CREATE TABLE IF NOT EXISTS sys_kb_eval_set (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(64)   NOT NULL,
  description VARCHAR(255)  NULL,
  create_time TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_kb_eval_set_name UNIQUE (name)
);
COMMENT ON TABLE sys_kb_eval_set IS '检索质量评测集(query+期望命中文档的用例分组)';

CREATE TABLE IF NOT EXISTS sys_kb_eval_case (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  set_id        BIGINT        NOT NULL,
  query         VARCHAR(512)  NOT NULL,
  expect_doc_id BIGINT        NOT NULL,
  expect_seq    INT           NULL,
  note          VARCHAR(255)  NULL,
  create_time   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_kb_eval_case_set FOREIGN KEY (set_id) REFERENCES sys_kb_eval_set (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_kb_eval_case_set ON sys_kb_eval_case (set_id);
COMMENT ON TABLE sys_kb_eval_case IS '检索评测用例(查询文本+期望命中文档id+可选期望块序号)';
COMMENT ON COLUMN sys_kb_eval_case.expect_doc_id IS '期望命中的kb_doc.id(创建时校验存在,文档删除不回溯清理)';
COMMENT ON COLUMN sys_kb_eval_case.expect_seq IS '期望块序号(NULL=不限定块序,仅按docId判定命中)';

CREATE TABLE IF NOT EXISTS sys_kb_eval_run (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  set_id          BIGINT        NOT NULL,
  set_name        VARCHAR(64)   NOT NULL,
  top_k           INT           NOT NULL DEFAULT 5,
  total_cases     INT           NOT NULL,
  hit_at_1        NUMERIC(5,4)  NOT NULL,
  hit_at_3        NUMERIC(5,4)  NOT NULL,
  hit_at_5        NUMERIC(5,4)  NOT NULL,
  mrr             NUMERIC(5,4)  NOT NULL,
  elapsed_ms      BIGINT        NOT NULL,
  rerank_active   SMALLINT      NOT NULL DEFAULT 0,
  embedding_model VARCHAR(128)  NOT NULL DEFAULT '',
  detail          TEXT          NOT NULL,
  create_time     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_kb_eval_run_set FOREIGN KEY (set_id) REFERENCES sys_kb_eval_set (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_kb_eval_run_set ON sys_kb_eval_run (set_id);
COMMENT ON TABLE sys_kb_eval_run IS '检索评测运行记录(快照语义:Hit@1/3/5+MRR+精排状态+逐用例明细JSON)';
COMMENT ON COLUMN sys_kb_eval_run.detail IS '逐用例结果JSON数组(query/expectDocId/expectSeq/rank/topHits)';

-- 2. C 菜单：系统管理下的「检索评测」（parent = System 目录）
INSERT INTO sys_menu (parent_id, menu_name, menu_type, title, icon, order_num,
                      path, component, perm, visible, keep_alive, affix_tab, authority, status)
SELECT 4, 'SystemKbEval', 'C', 'page.system.kbEval', 'ant-design:experiment-outlined', 13,
       '/system/kb-eval', '/system/kb-eval/index', '', 0, 0, 0, 'super,admin', 0
WHERE NOT EXISTS (SELECT 1 FROM sys_menu WHERE menu_name = 'SystemKbEval');

-- 3. F 按钮权限
INSERT INTO sys_menu (parent_id, menu_name, menu_type, title, perm, visible, status)
SELECT m.id, 'Perm_Kb_Eval_' || split_part(p.perm, ':', 3), 'F', p.perm, p.perm, 0, 0
FROM sys_menu m
CROSS JOIN (VALUES ('Kb:Eval:List'), ('Kb:Eval:Manage'), ('Kb:Eval:Run')) AS p(perm)
WHERE m.menu_name = 'SystemKbEval'
  AND NOT EXISTS (SELECT 1 FROM sys_menu f WHERE f.perm = p.perm);

-- 4. 授权给 super / admin
INSERT INTO sys_role_menu (role_id, menu_id)
SELECT r.id, m.id
FROM sys_role r
CROSS JOIN sys_menu m
WHERE r.role_key IN ('super', 'admin')
  AND (m.menu_name = 'SystemKbEval'
       OR (m.menu_type = 'F' AND m.perm LIKE 'Kb:Eval:%'))
  AND NOT EXISTS (SELECT 1 FROM sys_role_menu rm
                  WHERE rm.role_id = r.id AND rm.menu_id = m.id);
