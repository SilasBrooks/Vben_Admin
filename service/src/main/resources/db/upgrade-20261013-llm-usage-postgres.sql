-- 幂等：可重复执行（全部 IF NOT EXISTS 保护）；
--       新库由 schema-postgres.sql 覆盖，无需本脚本
-- ============================================================

-- 1. 建表（scene: chat=助手对话 / summarize=历史压缩；tokens 为 NULL 表示上游未返回 usage）
CREATE TABLE IF NOT EXISTS sys_llm_call_log (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scene             VARCHAR(16)   NOT NULL,
  model             VARCHAR(128)  NOT NULL,
  prompt_tokens     BIGINT        NULL,
  completion_tokens BIGINT        NULL,
  total_tokens      BIGINT        NULL,
  elapsed_ms        BIGINT        NOT NULL DEFAULT 0,
  create_time       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE sys_llm_call_log IS 'LLM调用用量日志(每次上游请求一条,仅成功调用,ping连通性测试不记)';
COMMENT ON COLUMN sys_llm_call_log.scene IS '调用场景:chat=助手对话,summarize=历史压缩';
COMMENT ON COLUMN sys_llm_call_log.model IS '模型名快照(当次激活配置的模型)';
COMMENT ON COLUMN sys_llm_call_log.prompt_tokens IS '输入token数(NULL=上游未返回usage)';
COMMENT ON COLUMN sys_llm_call_log.completion_tokens IS '输出token数(NULL=上游未返回usage)';
COMMENT ON COLUMN sys_llm_call_log.total_tokens IS '总token数(NULL=上游未返回usage)';
COMMENT ON COLUMN sys_llm_call_log.elapsed_ms IS '该上游请求耗时(毫秒)';

-- 2. 时间索引（仪表盘按日/月聚合扫描）
CREATE INDEX IF NOT EXISTS idx_llm_call_log_time ON sys_llm_call_log (create_time);
